TABLES = {"zh_CN": ZH, "en_US": EN}

# 当前语言。切语言时改它，然后重建界面（或调用 retranslate）。
_lang = "zh_CN"


def set_lang(code):
    global _lang
    if code in TABLES:
        _lang = code
    return _lang


def get_lang():
    return _lang


def t(key, **kw):
    """取一条文案。格式化参数用 `{name}` 占位。

    找不到 key 时返回 `⟨key⟩`，**不抛异常** ——
    少一行文案不该让整个界面起不来。同时会在控制台提醒，
    方便开发时发现漏翻的 key（用户看不到，只有跑源码时才有）。
    """
    table = TABLES.get(_lang) or ZH
    s = table.get(key)
    if s is None:
        s = ZH.get(key)
        if s is None:
            return "⟨%s⟩" % key
    if kw:
        try:
            return s.format(**kw)
        except (KeyError, IndexError):
            return s
    return s


def param_help(p):
    """参数的说明文字，按当前语言从 spec 里取。

    这是「参数说明只有一份」的落点：GUI 不自己抄一遍帮助文字，
    所以改 spec.py 的说明，界面和文档会同时更新。
    """
    if _lang == "en_US":
        return p.get("help_en") or p.get("help_zh") or ""
    return p.get("help_zh") or p.get("help_en") or ""
